package com.ccteam.graphql.entities;

import jakarta.persistence.*;
import lombok.Getter;
import lombok.Setter;

import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;

/**
 * Bike entity.
 *
 * @author yann39
 * @since 1.0.0
 */
@Getter
@Setter
@Entity
@Table(name = "bike")
public class Bike {

    /**
     * Database identifier (primary key) for this bike.
     * <p>
     * Generated by the database when the entity is persisted.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * The bike manufacturer, maximum 64 characters.
     */
    @Column(length = 64, nullable = false)
    private String manufacturer;

    /**
     * The bike model name, maximum 128 characters.
     */
    @Column(length = 128, nullable = false)
    private String modelName;

    /**
     * The bike engine size, in cubic centimeters (cc).
     */
    @Column
    private Integer engineSize;

    /**
     * The bike year of manufacture.
     */
    @Column
    private Integer year;

    /**
     * To identify if the bike is the member's current main bike.
     */
    @Column(nullable = false)
    private Boolean current = false;

    /**
     * Last known odometer reading, in kilometers.
     */
    @Column(name = "odometer_km")
    private Integer odometerKm;

    /**
     * Date of the last known odometer reading.
     */
    @Column
    private LocalDateTime odometerUpdatedOn;

    /**
     * The bike's owner.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "member_id")
    private Member member;

    /**
     * Maintenances of the bike, deleted with it.
     * <p>
     * Only mapped for the cascade, maintenances are created and fetched through their own repository.
     */
    @OneToMany(mappedBy = "bike", fetch = FetchType.LAZY, cascade = CascadeType.REMOVE)
    private List<Maintenance> maintenances = new ArrayList<>();

    /**
     * Equipments of the bike, deleted with it.
     * <p>
     * Only mapped for the cascade, equipments are created and fetched through their own repository.
     */
    @OneToMany(mappedBy = "bike", fetch = FetchType.LAZY, cascade = CascadeType.REMOVE)
    private List<BikeEquipment> equipments = new ArrayList<>();

}
